    THROW 52003, 'A tabela dbo.DISPONIBILIDADE_AJUDANTE não existe neste banco.', 1;
IF OBJECT_ID('dbo.PERFIL_ACESSO','U') IS NULL
    THROW 52004, 'A tabela dbo.PERFIL_ACESSO não existe neste banco.', 1;
